	private static volatile boolean polish = true;

	private final String pl;
	private final String en;

	Msg(String pl, String en) {
		this.pl = pl;
		this.en = en;
	}

	public static void setLanguage(String code) {
		polish = !"en".equalsIgnoreCase(code);
	}

	public String text(Object... args) {
		return String.format(Locale.ROOT, polish ? pl : en, args);
	}

	String pattern(boolean inPolish) {
		return inPolish ? pl : en;
	}
